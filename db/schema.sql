BEGIN;

-- ------------------------------------------------------------
-- Cargos / setores com salario fixo
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS positions (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          text NOT NULL UNIQUE,
  setor         text,
  salario_base  numeric(12,2) NOT NULL CHECK (salario_base >= 0),
  descricao     text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Funcionarios
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS employees (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                    text NOT NULL,
  cpf                     text NOT NULL UNIQUE,
  rg                      text,
  ctps_numero             text,
  pis_pasep               text,
  foto_url                text,
  rg_frente_url           text,
  rg_verso_url            text,
  cpf_doc_url             text,
  comprovante_endereco_url text,
  ctps_doc_url            text,
  data_nascimento         date,
  data_admissao           date,
  telefone                text,
  email                   text,
  cargo                   text,
  cargo_id                bigint REFERENCES positions(id) ON DELETE SET NULL,
  salario                 numeric(12,2) CHECK (salario IS NULL OR salario >= 0),
  salario_personalizado   boolean NOT NULL DEFAULT false,
  salario_moeda           text NOT NULL DEFAULT 'BRL',
  setor                   text,
  status                  text NOT NULL DEFAULT 'Sem dados'
                          CHECK (status IN (
                            'Sem dados',
                            'Pendente de Documentos',
                            'Aprovado pelo RH',
                            'Enviado para Contabilidade',
                            'Ativo',
                            'Inativo',
                            'Afastado',
                            'Férias'
                          )),
  vinculo                 text NOT NULL DEFAULT 'Ativo'
                          CHECK (vinculo IN ('Ativo', 'Inativo', 'Demitido', 'Afastado', 'Férias')),
  cep                     text,
  logradouro              text,
  numero                  text,
  complemento             text,
  bairro                  text,
  cidade                  text,
  uf                      text,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE employees ADD COLUMN IF NOT EXISTS data_admissao date;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS salario_personalizado boolean NOT NULL DEFAULT false;

-- ------------------------------------------------------------
-- Usuarios da aplicacao (substitui auth.users do Supabase)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profiles (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username      text NOT NULL UNIQUE,
  email         text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role          text NOT NULL DEFAULT 'user'
                CHECK (role IN ('admin', 'gestor', 'manager', 'user')),
  employee_id   bigint UNIQUE REFERENCES employees(id) ON DELETE SET NULL,
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Arquivos diversos (certificados, docs de filhos, outros)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS employee_documents (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  tipo           text NOT NULL CHECK (tipo IN ('certificado', 'doc_filho', 'outro')),
  titulo         text NOT NULL,
  url            text NOT NULL,
  mime           text,
  tamanho_bytes  bigint CHECK (tamanho_bytes IS NULL OR tamanho_bytes > 0),
  created_at     timestamptz NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Indices
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_positions_setor        ON positions (setor);
CREATE INDEX IF NOT EXISTS idx_employees_name         ON employees (name);
CREATE INDEX IF NOT EXISTS idx_employees_setor        ON employees (setor);
CREATE INDEX IF NOT EXISTS idx_employees_status       ON employees (status);
CREATE INDEX IF NOT EXISTS idx_employees_email        ON employees (email);
CREATE INDEX IF NOT EXISTS idx_employees_cep          ON employees (cep);
CREATE INDEX IF NOT EXISTS idx_employees_pis_pasep    ON employees (pis_pasep);
CREATE INDEX IF NOT EXISTS idx_employees_ctps_numero  ON employees (ctps_numero);
CREATE INDEX IF NOT EXISTS idx_employees_cargo_id     ON employees (cargo_id);
CREATE INDEX IF NOT EXISTS idx_employees_salario      ON employees (salario);
CREATE INDEX IF NOT EXISTS idx_profiles_role          ON profiles (role);
CREATE INDEX IF NOT EXISTS idx_emp_docs_employee_id   ON employee_documents (employee_id);
CREATE INDEX IF NOT EXISTS idx_emp_docs_tipo          ON employee_documents (tipo);

-- ------------------------------------------------------------
-- Funcoes e triggers
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION sync_salario_from_position()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  pos positions%ROWTYPE;
BEGIN
  IF NEW.cargo_id IS NOT NULL THEN
    SELECT * INTO pos FROM positions WHERE id = NEW.cargo_id;
    IF FOUND THEN
      NEW.cargo := pos.nome;
      NEW.setor := COALESCE(pos.setor, NEW.setor);
      IF NEW.salario_personalizado IS DISTINCT FROM true THEN
        NEW.salario := pos.salario_base;
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_employees_updated_at ON employees;
CREATE TRIGGER trg_employees_updated_at
  BEFORE UPDATE ON employees
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_employees_sync_salario ON employees;
CREATE TRIGGER trg_employees_sync_salario
  BEFORE INSERT OR UPDATE OF cargo_id, salario_personalizado ON employees
  FOR EACH ROW EXECUTE FUNCTION sync_salario_from_position();

DROP TRIGGER IF EXISTS trg_positions_updated_at ON positions;
CREATE TRIGGER trg_positions_updated_at
  BEFORE UPDATE ON positions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_profiles_updated_at ON profiles;
CREATE TRIGGER trg_profiles_updated_at
  BEFORE UPDATE ON profiles
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
